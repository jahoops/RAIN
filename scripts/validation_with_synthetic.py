def load_submission_file(submission_path):
    """Load a submission file and return as DataFrame"""
    if not os.path.exists(submission_path):
        print(f"Submission file not found: {submission_path}")
        return None
    
    try:
        submission_df = pd.read_csv(submission_path)
        print(f"Loaded submission with {len(submission_df)} predictions")
        return submission_df
    except Exception as e:
        print(f"Error loading submission file: {e}")
        return None

def load_synthetic_data(method='bootstrap'):
    """Load synthetic data generated by the specified method"""
    synthetic_path = f"data/synthetic_{method}.csv"
    
    if not os.path.exists(synthetic_path):
        print(f"Synthetic data file not found: {synthetic_path}")
        print(f"Please generate it first using: python synthetic_data_generator.py --method {method}")
        return None
    
    try:
        synthetic_df = pd.read_csv(synthetic_path)
        print(f"Loaded synthetic data with {len(synthetic_df)} samples")
        return synthetic_df
    except Exception as e:
        print(f"Error loading synthetic data: {e}")
        return None

def train_model_on_synthetic(synthetic_df, model_type='xgboost'):
    """Train a model on synthetic data"""
    from data_loader import preprocess_data
    
    # Check if model_type is a file path and extract just the model name part
    if isinstance(model_type, str) and os.path.exists(model_type):
        # Extract just the base filename, without path or extension
        # Remove any directory structure and use only the filename without extension
        model_type_clean = os.path.splitext(os.path.basename(model_type))[0]
        # Remove any special characters that shouldn't be in filenames
        model_type_clean = ''.join(c for c in model_type_clean if c.isalnum() or c in ['_', '-'])
        print(f"Using clean model name: {model_type_clean}")
    else:
        model_type_clean = model_type
    
    # Preprocess the synthetic data
    synthetic_df, _ = preprocess_data(synthetic_df, None)
    
    # Check if rainfall_original exists (for binary converted data)
    target_col = 'rainfall'
    if 'rainfall_original' in synthetic_df.columns:
        print("Found original rainfall values, will use these for regression metrics")
        regression_targets = synthetic_df['rainfall_original']
    else:
        regression_targets = synthetic_df['rainfall']
    
    # Prepare features and target
    X = synthetic_df.drop(['id', 'rainfall', 'rainfall_original'], axis=1, errors='ignore')
    y = synthetic_df[target_col]
    
    # Check if target is binary or continuous
    unique_values = np.unique(y)
    is_binary = len(unique_values) <= 2
    
    print(f"Training {model_type} model on {len(X)} synthetic samples with {X.shape[1]} features")
    print(f"Target type: {'binary' if is_binary else 'continuous'}")
    
    # Train model based on specified type
    if model_type == 'xgboost':
        import xgboost as xgb
        if is_binary:
            model = xgb.XGBClassifier(
                n_estimators=100,
                learning_rate=0.05,
                max_depth=4,
                subsample=0.8,
                colsample_bytree=0.8,
                random_state=42
            )
        else:
            model = xgb.XGBRegressor(
                n_estimators=100,
                learning_rate=0.05,
                max_depth=4,
                subsample=0.8,
                colsample_bytree=0.8,
                random_state=42
            )
    elif model_type == 'lightgbm':
        import lightgbm as lgb
        if is_binary:
            model = lgb.LGBMClassifier(
                n_estimators=100,
                learning_rate=0.05,
                max_depth=4,
                subsample=0.8,
                colsample_bytree=0.8,
                random_state=42
            )
        else:
            model = lgb.LGBMRegressor(
                n_estimators=100,
                learning_rate=0.05,
                max_depth=4,
                subsample=0.8,
                colsample_bytree=0.8,
                random_state=42
            )
    elif model_type == 'catboost':
        from catboost import CatBoostClassifier, CatBoostRegressor
        if is_binary:
            model = CatBoostClassifier(
                iterations=100,
                learning_rate=0.05,
                depth=4,
                subsample=0.8,
                colsample_bylevel=0.8,
                random_state=42,
                verbose=0
            )
        else:
            model = CatBoostRegressor(
                iterations=100,
                learning_rate=0.05,
                depth=4,
                subsample=0.8,
                colsample_bylevel=0.8,
                random_state=42,
                verbose=0
            )
    else:
        from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
        if is_binary:
            model = RandomForestClassifier(
                n_estimators=100,
                max_depth=4,
                random_state=42
            )
        else:
            model = RandomForestRegressor(
                n_estimators=100,
                max_depth=4,
                random_state=42
            )
    
    # Fit the model
    model.fit(X, y)
    
    # Evaluate on training data
    if is_binary:
        train_preds = model.predict_proba(X)[:, 1]
        train_auc = roc_auc_score(y, train_preds)
        print(f"Training AUC: {train_auc:.4f}")
    else:
        train_preds = model.predict(X)
        train_r2 = r2_score(y, train_preds)
        train_mse = mean_squared_error(y, train_preds)
        print(f"Training R²: {train_r2:.4f}, MSE: {train_mse:.4f}")
    
    # Create a directory to save models if it doesn't exist
    os.makedirs('models', exist_ok=True)
    
    # Save the model using the clean model name
    model_path = f'models/synthetic_{model_type_clean}_model.pkl'
    
    # Ensure the directory for this path exists
    os.makedirs(os.path.dirname(os.path.abspath(model_path)), exist_ok=True)
    
    # Use a safer way to write the file
    with open(model_path, 'wb') as f:
        pickle.dump(model, f)
    print(f"Model saved to {model_path}")
    
    return model, X.columns.tolist()

def apply_model_to_synthetic_test(model, feature_names, synthetic_test_df):
    """Apply a trained model to synthetic test data"""
    if 'rainfall' not in synthetic_test_df.columns:
        print("Error: Synthetic test data does not contain 'rainfall' column")
        return None, None
    
    # Extract features and target
    X_test = synthetic_test_df[feature_names]
    y_test = synthetic_test_df['rainfall']
    
    # Check if binary or regression model
    is_binary = hasattr(model, 'predict_proba')
    
    # Make predictions
    if is_binary:
        test_preds = model.predict_proba(X_test)[:, 1]
        # Convert target to binary if needed
        unique_values = np.unique(y_test)
        if len(unique_values) > 2:
            print("Converting target to binary for AUC calculation")
            binary_target = (y_test > y_test.median()).astype(int)
        else:
            binary_target = y_test
            
        # Calculate AUC
        test_auc = roc_auc_score(binary_target, test_preds)
        print(f"Test AUC on synthetic data: {test_auc:.4f}")
        return test_preds, test_auc
    else:
        test_preds = model.predict(X_test)
        test_r2 = r2_score(y_test, test_preds)
        test_mse = mean_squared_error(y_test, test_preds)
        print(f"Test R²: {test_r2:.4f}, MSE: {test_mse:.4f}")
        return test_preds, test_r2

def compare_with_submission(synthetic_df, submission_df):
    """Compare synthetic data predictions with submission file predictions"""
    if 'id' not in synthetic_df.columns or 'id' not in submission_df.columns:
        print("Error: ID columns required in both dataframes for comparison")
        return None
    
    # Merge dataframes on ID
    common_ids = set(synthetic_df['id']).intersection(set(submission_df['id']))
    if len(common_ids) == 0:
        # No common IDs, try to use closest value approach
        print("No common IDs found between synthetic data and submission")
        print("Attempting to match by positions instead...")
        
        # Use the smaller dataset's size to avoid index errors
        n_samples = min(len(synthetic_df), len(submission_df))
        
        # Match by position in file
        synthetic_subset = synthetic_df.iloc[:n_samples].copy()
        submission_subset = submission_df.iloc[:n_samples].copy()
        
        # Create correlation between synthetic rainfall and submission predictions
        correlation = np.corrcoef(synthetic_subset['rainfall'], submission_subset['rainfall'])[0, 1]
        print(f"Correlation between synthetic data and submission predictions: {correlation:.6f}")
        
        # Create a plot
        plt.figure(figsize=(10, 6))
        plt.scatter(synthetic_subset['rainfall'], submission_subset['rainfall'], alpha=0.5)
        plt.xlabel('Synthetic Data Rainfall')
        plt.ylabel('Submission Predictions')
        plt.title(f'Synthetic vs Submission (Correlation: {correlation:.6f})')
        plt.grid(True)
        os.makedirs('plots', exist_ok=True)
        plt.savefig('plots/synthetic_vs_submission.png')
        
        # Calculate AUC if the data seems suitable for classification
        try:
            # Convert to binary if not already
            binary_target = (synthetic_subset['rainfall'] > synthetic_subset['rainfall'].median()).astype(int)
            auc = roc_auc_score(binary_target, submission_subset['rainfall'])
            print(f"AUC score of submission predictions vs. synthetic binary target: {auc:.6f}")
            
            if auc < 0.5:
                print("Warning: AUC is below 0.5, indicating worse than random predictions.")
                print("This could mean the synthetic data is not representative or needs adjustment.")
        except Exception as e:
            print(f"Could not calculate AUC: {e}")
        
        return correlation
    else:
        print(f"Found {len(common_ids)} common IDs between synthetic data and submission")
        
        # Filter to only common IDs
        synthetic_subset = synthetic_df[synthetic_df['id'].isin(common_ids)].copy()
        submission_subset = submission_df[submission_df['id'].isin(common_ids)].copy()
        
        # Sort both by ID for proper alignment
        synthetic_subset.sort_values('id', inplace=True)
        submission_subset.sort_values('id', inplace=True)
        
        # Calculate correlation
        correlation = np.corrcoef(synthetic_subset['rainfall'], submission_subset['rainfall'])[0, 1]
        print(f"Correlation between synthetic data and submission predictions: {correlation:.6f}")
        
        # Create a plot
        plt.figure(figsize=(10, 6))
        plt.scatter(synthetic_subset['rainfall'], submission_subset['rainfall'], alpha=0.5)
        plt.xlabel('Synthetic Data Rainfall')
        plt.ylabel('Submission Predictions')
        plt.title(f'Synthetic vs Submission (Correlation: {correlation:.6f})')
        plt.grid(True)
        os.makedirs('plots', exist_ok=True)
        plt.savefig('plots/synthetic_vs_submission.png')
        
        # Calculate AUC if the data seems suitable for classification
        try:
            # Convert to binary if not already
            if synthetic_subset['rainfall'].nunique() > 2:
                binary_target = (synthetic_subset['rainfall'] > synthetic_subset['rainfall'].median()).astype(int)
            else:
                binary_target = synthetic_subset['rainfall']
                
            auc = roc_auc_score(binary_target, submission_subset['rainfall'])
            print(f"AUC score of submission predictions vs. synthetic binary target: {auc:.6f}")
            
            if auc < 0.5:
                print("Warning: AUC is below 0.5, indicating worse than random predictions.")
                print("This could mean the synthetic data is not representative or needs adjustment.")
        except Exception as e:
            print(f"Could not calculate AUC: {e}")
        
        return correlation

