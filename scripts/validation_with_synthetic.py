def validate_with_synthetic_data(model_name='xgboost', synthetic_method='bootstrap', feature_strategy='all'):
    """Main function to validate models using synthetic data"""
    # Check if model_name is a file path (submission file)
    if isinstance(model_name, str) and os.path.exists(model_name):
        print(f"Detected submission file path: {model_name}")
        submission_df = load_submission_file(model_name)
        if submission_df is None:
            return None
            
        # Load synthetic data directly from test set if it exists
        synthetic_test_path = '/home/USER/Projects/RAIN/data/synthetic_test_set.csv'
        if os.path.exists(synthetic_test_path):
            synthetic_df = pd.read_csv(synthetic_test_path)
            print(f"Loaded existing synthetic test set with {len(synthetic_df)} samples")
        else:
            # Or load from method-specific file
            synthetic_df = load_synthetic_data(method=synthetic_method)
            if synthetic_df is None:
                return None
            
        # Compare submission directly with synthetic data
        correlation = compare_with_submission(synthetic_df, submission_df)
        return correlation
    else:
        # Original code for model validation
        print(f"Validating {model_name} model using {synthetic_method} synthetic data...")
        
        # Load synthetic data
        synthetic_df = load_synthetic_data(method=synthetic_method)
        if synthetic_df is None:
            return None
        
        # Split synthetic data into train and test
        from sklearn.model_selection import train_test_split
        synthetic_train, synthetic_test = train_test_split(synthetic_df, test_size=0.2, random_state=42)
        
        print(f"Split synthetic data: {len(synthetic_train)} train, {len(synthetic_test)} test samples")
        
        # Train model on synthetic training data
        model, feature_names = train_model_on_synthetic(synthetic_train, model_type=model_name)
        
        # Apply model to synthetic test data
        test_preds, test_auc = apply_model_to_synthetic_test(model, feature_names, synthetic_test)
        
        # Find the best submission file
        submission_dir = 'data'
        submission_files = [f for f in os.listdir(submission_dir) if f.startswith('submission_') and f.endswith('.csv')]
        
        if submission_files:
            print(f"Found {len(submission_files)} submission files")
            
            best_correlation = -1
            best_submission = None
            
            for submission_file in submission_files:
                submission_path = os.path.join(submission_dir, submission_file)
                print(f"\nAnalyzing submission file: {submission_file}")
                
                submission_df = load_submission_file(submission_path)
                if submission_df is None:
                    continue
                
                # Compare with synthetic test set
                correlation = compare_with_submission(synthetic_test, submission_df)
                
                if correlation is not None and correlation > best_correlation:
                    best_correlation = correlation
                    best_submission = submission_file
            
            if best_submission:
                print(f"\nBest submission file: {best_submission} (correlation: {best_correlation:.6f})")
            else:
                print("\nNo valid submission files found for comparison")
        else:
            print("No submission files found in the data directory")
        
        # Return the test AUC as a metric of synthetic validation performance
        return test_auc

