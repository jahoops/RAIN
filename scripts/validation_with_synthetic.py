def create_synthetic_test_set(n_samples=2000, method='ensemble'):
    """
    Create a synthetic test set specifically for validation purposes
    
    Args:
        n_samples: Number of samples to generate
        method: Generation method ('ensemble', 'bootstrap', 'copula', etc.)
        
    Returns:
        DataFrame: Synthetic test data with optimal properties for validation
    """
    print(f"Generating improved synthetic test set with {n_samples} samples using {method} method...")
    
    # Load the original training data to extract distributions
    from data_loader import load_data, preprocess_data
    train_df, _ = load_data()
    train_df, _ = preprocess_data(train_df, None)
    
    # Load any existing submissions to improve synthetic data
    submission_files = []
    submissions_dir = '/home/USER/Projects/RAIN/data/'
    for file in os.listdir(submissions_dir):
        if file.startswith('submission_') and file.endswith('.csv'):
            submission_files.append(os.path.join(submissions_dir, file))
    
    submissions = []
    for file in submission_files[:5]:  # Use up to 5 different submissions for diversity
        try:
            sub_df = pd.read_csv(file)
            submissions.append(sub_df)
            print(f"Loaded submission file: {file}")
        except Exception as e:
            print(f"Couldn't load {file}: {e}")
    
    # Extract IDs from submissions to ensure overlap
    common_ids = set()
    if submissions:
        common_ids = set(submissions[0]['id'])
        for sub_df in submissions[1:]:
            common_ids = common_ids.intersection(set(sub_df['id']))
        print(f"Found {len(common_ids)} common IDs across submissions")
    
    # Start with a basic synthetic set
    if method == 'ensemble':
        # Use multiple methods and combine results
        synthetic_dfs = []
        methods = ['bootstrap', 'copula', 'parametric', 'weather']
        samples_per_method = n_samples // len(methods)
        
        for m in methods:
            try:
                from synthetic_data_generator import generate_synthetic_data
                df = generate_synthetic_data(method=m, n_samples=samples_per_method)
                if not df.empty:
                    # Ensure IDs don't conflict
                    df['id'] = df['id'] + 10000 * (methods.index(m) + 1)
                    synthetic_dfs.append(df)
            except Exception as e:
                print(f"Error generating data with method {m}: {e}")
        
        if not synthetic_dfs:
            print("Failed to generate synthetic data with any method")
            return None
        
        synthetic_df = pd.concat(synthetic_dfs, ignore_index=True)
    else:
        # Use a single method
        try:
            from synthetic_data_generator import generate_synthetic_data
            synthetic_df = generate_synthetic_data(method=method, n_samples=n_samples)
        except Exception as e:
            print(f"Error generating synthetic data: {e}")
            return None
    
    # Add IDs from real submissions to ensure common validation points
    if common_ids:
        # Add common IDs to synthetic data (replace some existing rows)
        n_common = min(len(common_ids), n_samples // 3)  # Use up to 1/3 of data
        common_id_list = list(common_ids)[:n_common]
        
        # For each common ID, create a synthetic entry
        common_rows = []
        for i, id_val in enumerate(common_id_list):
            # Take features from synthetic data but use the ID from submissions
            if i < len(synthetic_df):
                new_row = synthetic_df.iloc[i].copy()
                new_row['id'] = id_val
                common_rows.append(new_row)
        
        # Create DataFrame with common IDs
        common_df = pd.DataFrame(common_rows)
        
        # Replace some rows in synthetic_df with common_df
        synthetic_df = pd.concat([synthetic_df[n_common:], common_df], ignore_index=True)
    
    # Improve rainfall distribution to match real data better
    if 'rainfall' in synthetic_df.columns and 'rainfall' in train_df.columns:
        # Store original rainfall for regression metrics
        synthetic_df['rainfall_original'] = synthetic_df['rainfall'].copy()
        
        # Rainfall in training data is often binary (0/1) - match this distribution
        # Count zeros and ones in training data
        train_zeros = (train_df['rainfall'] == 0).sum()
        train_ones = (train_df['rainfall'] == 1).sum()
        train_binary_ratio = train_zeros / (train_zeros + train_ones) if train_zeros + train_ones > 0 else 0.5
        
        # Determine if we should binarize based on training data
        if train_zeros + train_ones > 0.8 * len(train_df):  # If >80% of values are 0 or 1
            print("Detected binary rainfall pattern in training data. Adjusting synthetic data.")
            
            # Create binary rainfall using the same ratio
            threshold = np.percentile(synthetic_df['rainfall'], train_binary_ratio * 100)
            synthetic_df['rainfall'] = (synthetic_df['rainfall'] > threshold).astype(int)
        else:
            # Otherwise just normalize the distribution shape
            print("Adjusting rainfall distribution to match training data")
            
            # Rank-transform to match training distribution
            sorted_train = np.sort(train_df['rainfall'])
            sorted_synth = np.sort(synthetic_df['rainfall'])
            
            # Create mapping from synthetic to training distribution
            rank_map = {}
            for i, val in enumerate(sorted_synth):
                if i < len(sorted_train):
                    idx = min(int(i * len(sorted_train) / len(sorted_synth)), len(sorted_train) - 1)
                    rank_map[val] = sorted_train[idx]
            
            # Apply mapping (approximate)
            for val in np.unique(synthetic_df['rainfall']):
                if val in rank_map:
                    synthetic_df.loc[synthetic_df['rainfall'] == val, 'rainfall'] = rank_map[val]
    
    # Save the synthetic test set
    output_path = '/home/USER/Projects/RAIN/data/synthetic_test_set.csv'
    synthetic_df.to_csv(output_path, index=False)
    print(f"Saved improved synthetic test set with {len(synthetic_df)} samples to {output_path}")
    
    # Analyze the dataset
    analyze_synthetic_quality(synthetic_df)
    
    return synthetic_df

